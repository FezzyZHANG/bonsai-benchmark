import sys
import unicodedata

def ranges_for(pred):
    ranges = []
    start = None
    prev = None
    for cp in range(0x110000):
        if pred(cp):
            if start is None:
                start = cp
            prev = cp
        else:
            if start is not None:
                ranges.append((start, prev))
                start = None
    if start is not None:
        ranges.append((start, prev))
    return ranges

def cat(cp):
    return unicodedata.category(chr(cp))

letter = ranges_for(lambda cp: cat(cp).startswith("L"))
mark = ranges_for(lambda cp: cat(cp).startswith("M"))
number = ranges_for(lambda cp: cat(cp).startswith("N"))

# Unicode White_Space property (what Rust regex \s means)
WS = [0x09,0x0A,0x0B,0x0C,0x0D,0x20,0x85,0xA0,0x1680] + list(range(0x2000,0x200B)) + [0x2028,0x2029,0x202F,0x205F,0x3000]
wsset = set(WS)
whitespace = ranges_for(lambda cp: cp in wsset)

def emit(fh, name, ranges):
    fh.write("pub const %s = [_][2]u21{\n" % name)
    for a, b in ranges:
        fh.write("    .{ 0x%X, 0x%X },\n" % (a, b))
    fh.write("};\n\n")

with open("/workspace/src/unicode_tables.zig", "w") as fh:
    fh.write("// Generated by tools/gen_unicode.py from Python unicodedata %s\n" % unicodedata.unidata_version)
    fh.write("// Ranges are inclusive [start, end] over Unicode scalar values.\n\n")
    emit(fh, "letters", letter)
    emit(fh, "marks", mark)
    emit(fh, "numbers", number)
    emit(fh, "whitespace_ranges", whitespace)

print("unicode version", unicodedata.unidata_version)
print("letters", len(letter), "marks", len(mark), "numbers", len(number), "ws", len(whitespace))
